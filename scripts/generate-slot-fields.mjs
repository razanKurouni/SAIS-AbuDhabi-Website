/**
 * Generates src/content/slot-fields.ts: for every page section (keyed as
 * "<page id>/<slot>"), the list of fields that actually hold content in the
 * dataset. The Studio uses it to
 * hide the optional fields a section never uses, so editors only see what
 * the website renders.
 *
 *   npm run content:slot-fields
 *
 * Re-run it after content has been added to a field that was hidden. Fields
 * the website uses before they have content go in ALWAYS_SHOWN below, so a
 * re-run keeps them.
 */
import fs from "node:fs";
import path from "node:path";
import { createClient } from "@sanity/client";

const rootDir = process.cwd();

function loadEnvFile(fileName) {
  const filePath = path.join(rootDir, fileName);
  if (!fs.existsSync(filePath)) return;
  for (const rawLine of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const index = line.indexOf("=");
    process.env[line.slice(0, index).trim()] ||= line.slice(index + 1).trim();
  }
}
loadEnvFile(".env.local");

const client = createClient({
  projectId: process.env.NEXT_PUBLIC_SANITY_PROJECT_ID || "zpdqig01",
  dataset: process.env.NEXT_PUBLIC_SANITY_DATASET || "abudhabi",
  apiVersion: "2025-02-19",
  token: process.env.SANITY_AUTH_TOKEN,
  useCdn: false,
});

/** Fields the website renders that may still be empty in the dataset: "<page id>/<slot>" → level → fields. */
const ALWAYS_SHOWN = {
  "our-campus-page/outdoorSection": { heading: ["description"] },
  "school-reports-page/reports": { card: ["file", "image"] },
};

const isObject = (value) => Boolean(value) && typeof value === "object" && !Array.isArray(value);
const hasContent = (value) => {
  if (value === null || value === undefined || value === "") return false;
  if (Array.isArray(value)) return value.length > 0;
  // An uploaded file or image is a reference ({ asset: { _ref } }) and counts as content.
  if (isObject(value)) return Boolean(value._ref) || Object.keys(value).some((key) => !key.startsWith("_") && hasContent(value[key]));
  return true;
};
const contentKeys = (value) =>
  isObject(value) ? Object.keys(value).filter((key) => !key.startsWith("_") && hasContent(value[key])) : [];

const add = (target, keys) => keys.forEach((key) => target.add(key));
const sorted = (set) => [...set].sort();

const pages = await client.fetch(`*[_type == "page" && !(_id in path("drafts.**"))]`);

const slots = {};
const heroes = {};

for (const page of pages) {
  heroes[page._id] = {
    hero: sorted(new Set(contentKeys(page.hero))),
    heading: sorted(new Set(contentKeys(page.hero?.heading))),
  };

  for (const section of page.sections || []) {
    if (!section.slot) continue;
    const slot = `${page._id}/${section.slot}`;
    const entry = (slots[slot] ??= {
      section: new Set(),
      heading: new Set(),
      card: new Set(),
      cardEntry: new Set(),
      entry: new Set(),
    });
    add(entry.section, contentKeys(section).filter((key) => key !== "slot"));
    add(entry.heading, contentKeys(section.heading));
    for (const card of section.cards || []) {
      add(entry.card, contentKeys(card));
      for (const item of card.entries || []) add(entry.cardEntry, contentKeys(item));
    }
    for (const item of section.entries || []) add(entry.entry, contentKeys(item));
  }
}

for (const [slot, levels] of Object.entries(ALWAYS_SHOWN)) {
  if (!slots[slot]) continue;
  for (const [level, fields] of Object.entries(levels)) add(slots[slot][level], fields);
}

const output = Object.fromEntries(
  Object.entries(slots)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slot, sets]) => [
      slot,
      Object.fromEntries(Object.entries(sets).map(([level, set]) => [level, sorted(set)])),
    ]),
);

const file = `/**
 * GENERATED by scripts/generate-slot-fields.mjs — the fields each section
 * slot actually uses. The Studio hides the other (empty) fields of a section
 * so editors only see what the website renders.
 *
 * To expose a field for a slot, add its name here (or re-run the generator
 * after the field has content).
 */

export type SlotFieldLevels = {
  /** Fields on the section itself. */
  section: string[];
  /** Fields inside the section heading. */
  heading: string[];
  /** Fields on each card. */
  card: string[];
  /** Fields on entries nested inside cards. */
  cardEntry: string[];
  /** Fields on entries directly on the section. */
  entry: string[];
};

/** Keyed by "<page id>/<slot>". */
export const SLOT_FIELDS: Record<string, SlotFieldLevels> = ${JSON.stringify(output, null, 2)};

/** Hero fields used per page id. */
export const HERO_FIELDS: Record<string, { hero: string[]; heading: string[] }> = ${JSON.stringify(heroes, null, 2)};
`;

fs.writeFileSync(path.join(rootDir, "src/content/slot-fields.ts"), file);
console.log(`Wrote src/content/slot-fields.ts for ${Object.keys(output).length} slots and ${pages.length} pages.`);
